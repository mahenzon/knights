#!/usr/bin/env python3
"""Publish decoded production data and art without the optional research captures."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def prepare():
    source = json.loads((ROOT / 'data/game-source.json').read_text())
    campaign = source['campaign']
    enemies = source['enemies']
    scene = source['scene']
    enemy_followup = source['enemy_followup']
    fragments = source['fragments']
    smoke = source['smoke']
    shop_layout = source['shop_layout']
    map_details = source['map_details']
    levels = []
    for source in campaign['levels']:
        level = {k: source[k] for k in ('name', 'mapPosition', 'backgroundId', 'dayCount')}
        hint = map_details['hints'][len(levels)]
        assert hint['selected'] == len(levels)
        level['hint'] = next(d['text'] for d in hint['draws'] if d['op'] == 'text')
        level['difficulties'] = {}
        for difficulty, value in source['difficulties'].items():
            level['difficulties'][difficulty] = [
                {k: day[k] for k in ('dayNumber', 'durationSeconds', 'tripleSpawn', 'mirrorLevel',
                                    'enemyTypeTable', 'wave', 'enemyModifiers',
                                    'disabledShopCategories', 'artefactInitializers')}
                for day in value['days']
            ]
        levels.append(level)
    assert len(levels) == 12 and sum(l['dayCount'] for l in levels) == 193
    art = sorted(p.name for p in (ROOT / 'dist/assets').iterdir() if p.suffix in ('.png', '.jpg', '.wav', '.mp3', '.fnt'))
    records = enemies['records']
    data = {'levels': levels, 'enemySprites': [r['sprite_prefix'] for r in records],
            'enemyAnimations': enemy_followup['animation_bindings'],
            'enemyAnimationFps': [r['base_stats']['animation_fps'] for r in records],
            'fragmentSprites': [fragments['sprites'][str(i)] for i in range(15)],
            'smokeSprites': [smoke['sprites'][str(i)] for i in range(13)],
            'sounds': scene['sounds'],
            'scene': {'altar': scene['altar_idle'], 'gate': [d for d in scene['gate_idle'] if 'image' in d]},
            'assets': art, 'randomRules': campaign['randomRules'],
            'shop': {'items': campaign['shop']['items'], 'placements': campaign['shop']['purchasedArtefactPlacements'],
                     'layout': [{k: v[k] for k in ('index','active','x','y','width','scale','image')} for v in shop_layout['layout']]}}
    (ROOT / 'web/game-data.json').write_text(json.dumps(data, separators=(',', ':')))
    fields = ('hp', 'walk_speed', 'castle_hit_damage', 'base_kill_reward', 'pickup_radius', 'animation_fps', 'attack_range_offset', 'attack_cooldown')
    lines = ['// Generated by tools/prepare_game_data.py from executed original initializers.',
             '#![allow(clippy::excessive_precision)] // Preserve the recovered f32 values verbatim.',
             '#[rustfmt::skip]', 'pub const STATS: [[f32; 9]; 11] = [']
    for record in records:
        values = [float(record['base_stats'][k]) for k in fields] + [float(record['base_fields']['0xd4'])]
        lines.append('    [' + ', '.join(repr(v) for v in values) + '],')
    lines += ['];']
    lines += ['#[rustfmt::skip]', 'pub const ANIMATION_LIMITS: [[f32; 11]; 11] = [']
    for record in records:
        lines.append('    [' + ', '.join(repr(v) for v in record['animation_frame_limits']) + '],')
    lines += ['];']
    lines += ['#[rustfmt::skip]', 'pub const BLAST_SMOKE: [&[[f32; 7]]; 6] = [']
    for source, kind in [('projectile',4),('creep',4),('creep',10),('projectile',6),('fireball',0),('fireball',3)]:
        emitter = next(e for e in smoke['emitters'] if e['source']==source and e['kind']==kind and e.get('charge',.5)==.5)
        lines += ['    &[']
        for v in emitter['smokes']:
            values=[float(v['kind']),float(v['y']-240),v['size'],v['growth'],v['alpha'],v['fade'],float(v['additive'])]
            lines += ['        ['+', '.join(repr(x) for x in values)+'],']
        lines += ['    ],']
    lines += ['];']
    (ROOT / 'engine/src/data.rs').write_text('\n'.join(lines) + '\n')
    print(f'Prepared {len(levels)} castles, 193 days × 3 difficulties, {len(records)} enemy types, {len(art)} assets')

if __name__ == '__main__':
    prepare()
